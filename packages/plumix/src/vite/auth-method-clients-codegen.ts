import { isAbsolute } from "node:path";

import { relativeSpecifier } from "./editor-entry-codegen.js";

/** The slice of a plugin descriptor this reads. */
interface DeclaresAuthMethods {
  readonly authMethods?: readonly { readonly client?: string }[];
}

const HEADER = "// Generated by plumix — do not edit.\n";

/**
 * Imports each sign-in method's client half once, in plugin order, and mounts
 * them on `authClient`; `""` when none. An absolute path imports relative to
 * `entryDir`.
 */
export function authMethodClientsSource(
  entryDir: string,
  plugins: readonly DeclaresAuthMethods[],
): string {
  const specifiers = [
    ...new Set(
      plugins.flatMap((plugin) =>
        (plugin.authMethods ?? []).flatMap(({ client }) =>
          client === undefined ? [] : [client],
        ),
      ),
    ),
  ];
  if (specifiers.length === 0) return "";
  const imports = specifiers
    .map((specifier, i) => {
      const from = isAbsolute(specifier)
        ? relativeSpecifier(entryDir, specifier)
        : specifier;
      return `import c${i} from ${JSON.stringify(from)};\n`;
    })
    .join("");
  const locals = specifiers.map((_, i) => `c${i}`).join(", ");
  return (
    imports +
    'import { registerAuthMethodClients } from "plumix/auth/client";\n' +
    `registerAuthMethodClients([${locals}]);\n`
  );
}

/**
 * An island awaits this chunk before it mounts, so every half is registered
 * before any island renders, and a page whose islands never hydrate loads none.
 */
export function generateIslandsRendererEntrySource(
  entryDir: string,
  plugins: readonly DeclaresAuthMethods[],
): string {
  return (
    HEADER +
    authMethodClientsSource(entryDir, plugins) +
    'export * from "plumix/blocks/island-renderer";\n'
  );
}
