import {
  mkdirSync,
  mkdtempSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { optimizeDeps, resolveConfig } from "vite";
import { afterEach, beforeEach, describe, expect, test } from "vitest";

import { generateEditorEntrySource } from "./editor-entry-codegen.js";

const ENTRY_DIR = "/app/.plumix";

const ref = (module: string, exportName = "default") => ({
  module,
  exportName,
});

describe("generateEditorEntrySource", () => {
  test("no blocks → a bare bootEditor() call", () => {
    const source = generateEditorEntrySource(ENTRY_DIR, []);
    expect(source).toContain(
      'import { bootEditor } from "plumix/editor-runtime";',
    );
    expect(source).toContain("bootEditor();");
    expect(source).not.toContain("import pb");
  });

  test("default-import a default export", () => {
    const source = generateEditorEntrySource(ENTRY_DIR, [
      ref("@plumix/plugin-media/blocks"),
      ref("@acme/widgets/blocks"),
    ]);
    expect(source).toContain('import pb0 from "@plumix/plugin-media/blocks";');
    expect(source).toContain('import pb1 from "@acme/widgets/blocks";');
  });

  test("named-import a named export", () => {
    const source = generateEditorEntrySource(ENTRY_DIR, [
      ref("@plumix/plugin-media/blocks", "mediaBlocks"),
    ]);
    expect(source).toContain(
      'import { mediaBlocks as pb0 } from "@plumix/plugin-media/blocks";',
    );
  });

  test("imports a resolved file relative to the entry's folder", () => {
    const source = generateEditorEntrySource(ENTRY_DIR, [
      ref("/app/node_modules/media/dist/media-blocks.js", "mediaBlocks"),
      ref("/app/.plumix/local.ts"),
    ]);
    expect(source).toContain(
      'import { mediaBlocks as pb0 } from "../node_modules/media/dist/media-blocks.js";',
    );
    expect(source).toContain('import pb1 from "./local.ts";');
  });

  test("normalizes each import so a single spec or missing export can't crash the spread", () => {
    const source = generateEditorEntrySource(ENTRY_DIR, [ref("./blocks.js")]);
    // A single `registerBlock` spec becomes `[pb0]`, an array passes through,
    // a missing export becomes `[]` — never a non-iterable in the spread.
    expect(source).toContain(
      "bootEditor({ blocks: [...(Array.isArray(pb0) ? pb0 : pb0 ? [pb0] : [])], shortcodes: [] });",
    );
  });

  test("imports shortcode modules and hands them to bootEditor in order", () => {
    const source = generateEditorEntrySource(
      ENTRY_DIR,
      [],
      [ref("/app/plugin/shortcodes.ts", "shortcodes"), ref("/app/theme/sc.ts")],
    );
    expect(source).toContain(
      'import { shortcodes as ps0 } from "../plugin/shortcodes.ts";',
    );
    expect(source).toContain('import ps1 from "../theme/sc.ts";');
    // Plugin before theme: the canvas registry is last-write-wins.
    expect(source).toContain(
      "bootEditor({ blocks: [], shortcodes: [...(Array.isArray(ps0) ? ps0 : ps0 ? [ps0] : []), ...(Array.isArray(ps1) ? ps1 : ps1 ? [ps1] : [])] });",
    );
  });

  test("quotes specifiers via JSON.stringify", () => {
    const source = generateEditorEntrySource(ENTRY_DIR, [
      ref('weird"name/blocks'),
    ]);
    expect(source).toContain('import pb0 from "weird\\"name/blocks";');
  });

  test("always emits the do-not-edit header", () => {
    const source = generateEditorEntrySource(ENTRY_DIR, []);
    expect(source).toContain("Generated by plumix");
    expect(source).toContain("do not edit");
  });
});

describe("the generated editor entry under Vite's dependency scan", () => {
  let dir: string;

  beforeEach(() => {
    // Real path: the generator resolves modules to real paths, and on macOS
    // the temp dir sits behind a symlink.
    dir = realpathSync(
      mkdtempSync(join(tmpdir(), "plumix-editor-entry-scan-")),
    );
  });
  afterEach(() => {
    rmSync(dir, { recursive: true, force: true });
  });

  const write = (rel: string, content: string) => {
    const path = join(dir, rel);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content, "utf8");
  };

  test("prebundles what an installed plugin's block module imports", async () => {
    write(
      "node_modules/plumix/package.json",
      JSON.stringify({
        name: "plumix",
        type: "module",
        exports: { "./editor-runtime": "./editor-runtime.js" },
      }),
    );
    write(
      "node_modules/plumix/editor-runtime.js",
      "export function bootEditor() {}",
    );
    // CommonJS, like `react/jsx-runtime`: the browser can only import it once
    // Vite has prebundled it.
    write(
      "node_modules/cjs-dep/package.json",
      JSON.stringify({ name: "cjs-dep", main: "index.js" }),
    );
    write("node_modules/cjs-dep/index.js", "exports.jsx = () => null;");
    write(
      "node_modules/block-plugin/package.json",
      JSON.stringify({ name: "block-plugin", type: "module" }),
    );
    write(
      "node_modules/block-plugin/blocks.js",
      'import { jsx } from "cjs-dep";\nexport const blocks = [jsx];',
    );
    write(
      ".plumix/editor-entry.ts",
      generateEditorEntrySource(join(dir, ".plumix"), [
        ref(join(dir, "node_modules/block-plugin/blocks.js"), "blocks"),
      ]),
    );

    // Vite never discovers a dependency at request time when the importer is
    // inside node_modules, so the startup scan is the only way in.
    const config = await resolveConfig(
      {
        root: dir,
        configFile: false,
        logLevel: "silent",
        optimizeDeps: { entries: [".plumix/editor-entry.ts"] },
      },
      "serve",
    );
    // Deprecated because a dev server runs the scan itself; this is the one
    // call that runs it alone and returns what it found.
    // eslint-disable-next-line @typescript-eslint/no-deprecated
    const metadata = await optimizeDeps(config, true);

    expect(Object.keys(metadata.optimized)).toContain("cjs-dep");
  });
});
