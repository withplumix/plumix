// The one catalog compile: `plumix i18n compile` runs it, and so does the
// `plumix-compile-catalogs` bin that core, admin and admin-editor use — they
// sit upstream of `plumix` in the build graph, so calling it would form a
// cycle. Hand-written and shipped as-is rather than built from `src/`,
// because core compiles its own catalogs before it builds.
import { spawn } from "node:child_process";
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { basename, dirname, join } from "node:path";
import { pathToFileURL } from "node:url";

const CATALOG_DTS =
  "export declare const messages: Record<string, string | readonly string[]>;\n";

const INDEX_DTS =
  "export declare const catalogs: Readonly<Record<string, () => Promise<{ readonly messages: Record<string, string | readonly string[]> }>>>;\n";

/** @param {import("./index.d.mts").CompileCatalogsOptions} options */
export async function compileCatalogs({
  cwd,
  linguiBin,
  args = [],
  dts = false,
}) {
  const surfaces = await discoverSurfaces(cwd, linguiBin);
  const misnamed = surfaces.flatMap(misnamedCatalogs);
  if (misnamed.length > 0) return { ok: false, reason: misnamed.join("; ") };
  const result = await runLinguiCompile({ cwd, linguiBin, args, dts });
  if (!result.ok) return result;
  try {
    for (const surface of surfaces) writeIndex(surface, dts);
  } catch (cause) {
    return { ok: false, reason: `could not write a catalog index — ${cause}` };
  }
  return result;
}

/**
 * Each catalog path in the package's lingui config, with the locales its
 * `.po` files name. The config is read by the lingui that compiles it.
 */
async function discoverSurfaces(cwd, linguiBin) {
  const { getConfig } = await import(
    pathToFileURL(createRequire(linguiBin).resolve("@lingui/conf")).href
  );
  return getConfig({ cwd }).catalogs.map(({ path }) => {
    const dir = dirname(path);
    const [prefix, suffix] = basename(path).split("{locale}");
    return {
      dir,
      prefix,
      suffix,
      locales: discoverCatalogLocales(path),
    };
  });
}

/**
 * The locales a catalog path template ships: one per `.po` file its
 * `{locale}` placeholder matches. Lingui configs call it to list their
 * locales, so the files are the only record of them.
 *
 * @param {string} catalogPath an absolute catalog path template
 * @returns {string[]}
 */
export function discoverCatalogLocales(catalogPath) {
  const [prefix, suffix] = basename(catalogPath).split("{locale}");
  const ending = `${suffix}.po`;
  let files;
  try {
    files = readdirSync(dirname(catalogPath));
  } catch {
    return [];
  }
  return files
    .filter(
      (file) =>
        file.startsWith(prefix) &&
        file.endsWith(ending) &&
        file.length > prefix.length + ending.length,
    )
    .map((file) => file.slice(prefix.length, file.length - ending.length))
    .sort();
}

/**
 * A catalog only loads under its canonical BCP 47 name, so a file named
 * otherwise fails the compile rather than being renamed behind its author.
 */
function misnamedCatalogs({ prefix, suffix, locales }) {
  return locales.flatMap((locale) => {
    const file = `${prefix}${locale}${suffix}.po`;
    let canonical;
    try {
      [canonical] = Intl.getCanonicalLocales(locale.replaceAll("_", "-"));
    } catch {
      return [`\`${file}\` does not name a BCP 47 locale`];
    }
    return canonical === locale
      ? []
      : [`rename \`${file}\` to \`${prefix}${canonical}${suffix}.po\``];
  });
}

/**
 * `<dir>/index/<surface>.mjs`: a lazy loader per locale. In a folder of its
 * own, so a `locales/*.mjs` glob over the catalogs never reads it as one.
 */
function writeIndex({ dir, prefix, suffix, locales }, dts) {
  const name =
    `${prefix}${suffix}`.replace(/^[-_.]+|[-_.]+$/g, "") || "catalogs";
  const indexDir = join(dir, "index");
  mkdirSync(indexDir, { recursive: true });
  const loaders = locales.map(
    (locale) =>
      `  ${JSON.stringify(locale)}: () => import(${JSON.stringify(
        `../${prefix}${locale}${suffix}.mjs`,
      )}),\n`,
  );
  writeFileSync(
    join(indexDir, `${name}.mjs`),
    `// Generated by the catalog compile from the .po files beside it.\nexport const catalogs = {\n${loaders.join("")}};\n`,
  );
  if (dts) writeFileSync(join(indexDir, `${name}.d.mts`), INDEX_DTS);
}

function runLinguiCompile({ cwd, linguiBin, args, dts }) {
  return new Promise((resolve) => {
    // `--namespace es` emits ESM `.mjs`; without it lingui defaults to CJS
    // `.js`. No `--strict`, so missing translations fall back to source.
    // Output is captured to fail on a parse error, which lingui only warns
    // about.
    const child = spawn(
      process.execPath,
      [linguiBin, "compile", "--namespace", "es", ...args],
      { cwd, stdio: ["inherit", "pipe", "pipe"] },
    );

    let buffered = "";
    const tee = (stream, into) => {
      stream.on("data", (chunk) => {
        buffered += chunk.toString();
        into.write(chunk);
      });
    };
    tee(child.stdout, process.stdout);
    tee(child.stderr, process.stderr);

    child.once("error", (cause) => {
      resolve({ ok: false, reason: `failed to start lingui — ${cause}` });
    });

    // `close`, not `exit`: exit can fire before the last output chunk
    // arrives, and the parse-error marker may be in it.
    child.once("close", (code, signal) => {
      if (code !== 0) {
        const detail = signal ? `signal ${signal}` : `code ${code}`;
        resolve({ ok: false, reason: `lingui exited with ${detail}` });
        return;
      }
      if (/Compilation error/.test(buffered)) {
        resolve({ ok: false, reason: "parse error in a catalog" });
        return;
      }
      // Only static-import consumers (core's admin bar resolves catalogs
      // through the package `exports` map) need declarations. Glob
      // consumers infer the type from the `.mjs` directly, and a stub
      // would clash with lingui's `Messages`.
      if (dts) {
        try {
          writeDeclarations(join(cwd, "locales"));
        } catch (cause) {
          resolve({ ok: false, reason: `could not emit .d.mts — ${cause}` });
          return;
        }
      }
      resolve({ ok: true });
    });
  });
}

function writeDeclarations(localesDir) {
  for (const file of readdirSync(localesDir)) {
    if (!file.endsWith(".mjs")) continue;
    writeFileSync(
      join(localesDir, file.replace(/\.mjs$/, ".d.mts")),
      CATALOG_DTS,
    );
  }
}
