import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

interface ParentLocalesJson {
  readonly supplemental: {
    readonly parentLocales: {
      readonly parentLocale: Readonly<Record<string, string>>;
    };
  };
}

export const CLDR_PARENT_LOCALES_FILE = fileURLToPath(
  new URL("../src/i18n/cldr-parent-locales.ts", import.meta.url),
);

function installedParentLocales(): Readonly<Record<string, string>> {
  const require = createRequire(import.meta.url);
  const json =
    require("cldr-core/supplemental/parentLocales.json") as ParentLocalesJson;
  return json.supplemental.parentLocales.parentLocale;
}

/** Quoted only where Prettier would keep the quotes, so the output passes `format`. */
function propertyKey(locale: string): string {
  return /^[a-z]+$/.test(locale) ? locale : JSON.stringify(locale);
}

export function renderCldrParentLocales(): string {
  const entries = Object.entries(installedParentLocales()).sort(([a], [b]) =>
    a < b ? -1 : a > b ? 1 : 0,
  );
  const lines = entries.map(
    ([locale, parent]) =>
      `  ${propertyKey(locale)}: ${JSON.stringify(parent)},`,
  );
  return [
    "// Generated by `pnpm cldr:generate` from `cldr-core`'s parentLocales.",
    "// Don't edit by hand.",
    "",
    "/** CLDR's parent of each locale that has one other than its truncation; `und` is root. */",
    "export const CLDR_PARENT_LOCALES: Readonly<Record<string, string>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

if (import.meta.main) {
  await writeFile(CLDR_PARENT_LOCALES_FILE, renderCldrParentLocales());
}
